"""
Generate the five dataset YAML configs for a given data root.

The configs need absolute paths (ultralytics resolves relative dataset paths
against its own settings directory, not the repo, which is a common source of
silent "0 images found" runs). Absolute paths are machine-specific, so rather
than hand-editing five files whenever the project moves -- Windows dev box to
Colab, say -- they are regenerated from whatever root is passed in.

Usage:
    # local (default: <repo>/data/processed)
    python src/data/write_dataset_configs.py

    # Colab
    python src/data/write_dataset_configs.py --data-root /content/road-damage-detection/data/processed
"""

import argparse
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]
CONFIG_DIR = REPO_ROOT / "config"

CLASS_BLOCK = """nc: 4
names:
  0: D00
  1: D10
  2: D20
  3: D40
"""

TARGET_NOTES = {
    "czech": "Czech",
    "norway": ("Norway.\n# Note: Norway's images are high-resolution and rectangular, unlike the small\n"
               "# square images used elsewhere (see data/DATA_REPORT.md section 5). This is part\n"
               "# of the domain shift under study, not a bug."),
    "us": "United States",
    "china_drone": ("China (drone/aerial capture).\n"
                     "# Kept SEPARATE from china_motorbike (the project spec section 4.3: different capture\n"
                     "# modalities are a genuinely different domain -- do not merge blindly)."),
    "china_motorbike": ("China (vehicle-mounted capture).\n"
                         "# Kept SEPARATE from china_drone -- see the note above."),
}


def write_source(data_root: Path):
    path = CONFIG_DIR / "dataset_source.yaml"
    path.write_text(
        f"""# YOLOv8 dataset config for the SOURCE domain (India + Japan combined).
# GENERATED by src/data/write_dataset_configs.py -- do not hand-edit; rerun that
# script instead if the data moves. See data/split_report.json for exact counts.

train: {data_root.as_posix()}/source/images/train
val: {data_root.as_posix()}/source/images/val
test: {data_root.as_posix()}/source/images/test

{CLASS_BLOCK}""",
        encoding="utf-8",
    )
    return path


def write_subset(data_root: Path):
    path = CONFIG_DIR / "dataset_source_subset.yaml"
    path.write_text(
        f"""# Small SOURCE subset used ONLY for end-to-end pipeline validation
# (the project spec section 8). Built by src/data/make_subset.py.
# GENERATED by src/data/write_dataset_configs.py -- do not hand-edit.
#
# Numbers produced from this config are smoke-test artifacts, NOT results.
# They must never appear in the report or in any results table.

train: {data_root.as_posix()}/source_subset/images/train
val: {data_root.as_posix()}/source_subset/images/val
test: {data_root.as_posix()}/source_subset/images/test

{CLASS_BLOCK}""",
        encoding="utf-8",
    )
    return path


def write_target(data_root: Path, key: str):
    path = CONFIG_DIR / f"dataset_target_{key}.yaml"
    path.write_text(
        f"""# YOLOv8 dataset config for the TARGET zero-shot eval set: {TARGET_NOTES[key]}
# GENERATED by src/data/write_dataset_configs.py -- do not hand-edit.
#
# Whole labeled set, no train/val/test split: this data is only ever used for
# zero-shot evaluation and is never trained on. 'train' is required by the
# ultralytics dataset schema but unused -- it mirrors 'val' as a placeholder.

train: {data_root.as_posix()}/target/{key}/images
val: {data_root.as_posix()}/target/{key}/images

{CLASS_BLOCK}""",
        encoding="utf-8",
    )
    return path


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--data-root", default=str(REPO_ROOT / "data" / "processed"),
                    help="absolute path to the processed data directory")
    args = ap.parse_args()

    data_root = Path(args.data_root)
    CONFIG_DIR.mkdir(parents=True, exist_ok=True)

    written = [write_source(data_root), write_subset(data_root)]
    written += [write_target(data_root, k) for k in TARGET_NOTES]

    print(f"Data root: {data_root.as_posix()}")
    for p in written:
        print(f"  wrote {p.relative_to(REPO_ROOT)}")


if __name__ == "__main__":
    main()
