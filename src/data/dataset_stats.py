"""
Phase 1 script: compute per-class box counts, image size distributions, and
class-imbalance stats for the RDD2022 data actually on disk, then assemble
data/DATA_REPORT.md (combining these results with verify_dataset.py's output).

Must be run AFTER verify_dataset.py (this script reads data/verification_report.json).

Usage:
    python src/data/dataset_stats.py

Writes:
    data/class_distribution.json
    experiments/results/figures/class_counts_per_country.png
    experiments/results/figures/dropped_classes.png
    experiments/results/figures/image_size_distribution.png
    data/DATA_REPORT.md
"""

import json
import xml.etree.ElementTree as ET
from collections import defaultdict
from pathlib import Path

import matplotlib.pyplot as plt

REPO_ROOT = Path(__file__).resolve().parents[2]
DATA_DIR = REPO_ROOT / "data"
FIGURES_DIR = REPO_ROOT / "experiments" / "results" / "figures"

# The four CRDDC-2022 challenge classes this project trains on (CLAUDE.md section 4.2).
# Any other code (D43, D44, D50, ...) is counted separately and dropped before training.
TARGET_CLASSES = ["D00", "D10", "D20", "D40"]


def parse_country_annotations(country_dir: Path) -> dict:
    """Parse every train XML for one country. Returns per-class box counts
    (target + dropped-other), image sizes, and images-with-zero-boxes count."""
    xml_dir = country_dir / "train" / "annotations" / "xmls"
    class_counts = defaultdict(int)
    other_class_counts = defaultdict(int)
    widths = []
    heights = []
    num_images = 0
    num_images_with_no_boxes = 0

    for xml_path in sorted(xml_dir.glob("*.xml")):
        num_images += 1
        root = ET.parse(xml_path).getroot()

        size_tag = root.find("size")
        if size_tag is not None:
            w = size_tag.findtext("width")
            h = size_tag.findtext("height")
            if w and h:
                widths.append(int(w))
                heights.append(int(h))

        objects = root.findall("object")
        if not objects:
            num_images_with_no_boxes += 1
        for obj in objects:
            name = obj.findtext("name")
            if name in TARGET_CLASSES:
                class_counts[name] += 1
            else:
                other_class_counts[name] += 1

    return {
        "num_images": num_images,
        "num_images_with_no_boxes": num_images_with_no_boxes,
        "class_counts": dict(class_counts),
        "other_class_counts": dict(other_class_counts),
        "widths": widths,
        "heights": heights,
    }


def plot_class_counts_per_country(stats: dict):
    countries = list(stats.keys())
    fig, ax = plt.subplots(figsize=(10, 6))
    x = range(len(countries))
    bar_width = 0.2
    for i, cls in enumerate(TARGET_CLASSES):
        values = [stats[c]["class_counts"].get(cls, 0) for c in countries]
        ax.bar([xi + i * bar_width for xi in x], values, width=bar_width, label=cls)
    ax.set_xticks([xi + bar_width * 1.5 for xi in x])
    ax.set_xticklabels(countries, rotation=30, ha="right")
    ax.set_ylabel("Box count")
    ax.set_title("Per-class box counts by country (target classes only)")
    ax.legend()
    fig.tight_layout()
    fig.savefig(FIGURES_DIR / "class_counts_per_country.png", dpi=150)
    plt.close(fig)


def plot_dropped_classes(stats: dict):
    totals = defaultdict(int)
    for c in stats:
        for cls, cnt in stats[c]["other_class_counts"].items():
            totals[cls] += cnt
    if not totals:
        return
    codes = sorted(totals, key=lambda k: -totals[k])
    values = [totals[c] for c in codes]
    fig, ax = plt.subplots(figsize=(8, 5))
    ax.bar(codes, values, color="darkred")
    ax.set_ylabel("Box count (dropped)")
    ax.set_title("Non-standard class codes dropped (all countries combined)")
    fig.tight_layout()
    fig.savefig(FIGURES_DIR / "dropped_classes.png", dpi=150)
    plt.close(fig)


def plot_image_size_distribution(stats: dict):
    fig, ax = plt.subplots(figsize=(8, 8))
    for country, s in stats.items():
        if s["widths"]:
            ax.scatter(s["widths"], s["heights"], s=4, alpha=0.4, label=country)
    ax.set_xlabel("width (px)")
    ax.set_ylabel("height (px)")
    ax.set_title("Image size distribution by country")
    ax.legend(markerscale=3)
    fig.tight_layout()
    fig.savefig(FIGURES_DIR / "image_size_distribution.png", dpi=150)
    plt.close(fig)


def build_data_report(verify_report: dict, stats: dict, out_path: Path):
    lines = []
    lines.append("# Data Report — RDD2022\n")
    lines.append(
        "Auto-generated by `src/data/verify_dataset.py` and `src/data/dataset_stats.py`. "
        "Every number below comes from an actual scan of the data on disk "
        f"(`{verify_report['data_dir']}`), run on this machine.\n"
    )

    lines.append("## 1. Directory structure found\n")
    lines.append(
        "Dataset is stored at `data/<country>/` (not `data/raw/RDD2022/<country>/` as the "
        "original CLAUDE.md sketch shows — confirmed deviation, scripts point at `data/` directly). "
        "Each country has `train/images/` + `train/annotations/xmls/`; most also have an unlabeled "
        "`test/images/` folder (the held-out CRDDC challenge test set — not used, per CLAUDE.md "
        "section 4.3 and section 12).\n"
    )

    lines.append("## 2. Per-country counts, orphans, parse failures\n")
    lines.append("| Country | Train images | Train XMLs | Test images (unlabeled) | Orphan images | Orphan XMLs | XML parse failures | Filename mismatches |")
    lines.append("|---|---|---|---|---|---|---|---|")
    for c in verify_report["countries"]:
        lines.append(
            f"| {c['country']} | {c['num_train_images']} | {c['num_train_xmls']} | "
            f"{c['num_test_images']} | {c['num_orphan_images_no_xml']} | "
            f"{c['num_orphan_xmls_no_image']} | {c['num_xml_parse_failures']} | "
            f"{c['num_xml_filename_mismatches']} |"
        )
    total_train = sum(c["num_train_images"] for c in verify_report["countries"])
    lines.append(f"\n**Total labeled train images across all countries: {total_train}**\n")

    lines.append("## 3. Per-class box counts (target classes only)\n")
    lines.append("| Country | D00 | D10 | D20 | D40 | Total | Images w/ zero boxes |")
    lines.append("|---|---|---|---|---|---|---|")
    grand_totals = defaultdict(int)
    for country, s in stats.items():
        row = [s["class_counts"].get(cls, 0) for cls in TARGET_CLASSES]
        for cls, v in zip(TARGET_CLASSES, row):
            grand_totals[cls] += v
        lines.append(
            f"| {country} | {row[0]} | {row[1]} | {row[2]} | {row[3]} | {sum(row)} | "
            f"{s['num_images_with_no_boxes']} |"
        )
    total_row = [grand_totals[cls] for cls in TARGET_CLASSES]
    lines.append(f"| **TOTAL** | **{total_row[0]}** | **{total_row[1]}** | **{total_row[2]}** | **{total_row[3]}** | **{sum(total_row)}** | |")
    lines.append(
        "\nNote the class imbalance above (CLAUDE.md section 4.3): D40 (pothole) is the rarest class "
        "in most countries. This must be accounted for in training/evaluation analysis.\n"
    )

    lines.append("## 4. Dropped (non-standard) class codes\n")
    other_totals = defaultdict(int)
    for country, s in stats.items():
        for cls, cnt in s["other_class_counts"].items():
            other_totals[cls] += cnt
    if other_totals:
        lines.append("| Code | Total boxes dropped |")
        lines.append("|---|---|")
        for cls in sorted(other_totals, key=lambda k: -other_totals[k]):
            lines.append(f"| {cls} | {other_totals[cls]} |")
        lines.append(f"\n**Total dropped boxes: {sum(other_totals.values())}**\n")
    else:
        lines.append("No non-standard class codes found in this dataset.\n")

    lines.append("## 5. Image size distribution\n")
    lines.append("| Country | Min (WxH) | Max (WxH) | Distinct sizes |")
    lines.append("|---|---|---|---|")
    for country, s in stats.items():
        if not s["widths"]:
            continue
        sizes = list(zip(s["widths"], s["heights"]))
        min_size = min(sizes, key=lambda wh: wh[0] * wh[1])
        max_size = max(sizes, key=lambda wh: wh[0] * wh[1])
        distinct = len(set(sizes))
        lines.append(f"| {country} | {min_size[0]}x{min_size[1]} | {max_size[0]}x{max_size[1]} | {distinct} |")
    lines.append(
        "\nAs expected from CLAUDE.md section 4.3, Norway's images are high-resolution and "
        "differ from the roughly-square, smaller images used by other countries — see "
        "`experiments/results/figures/image_size_distribution.png`. This is a real part of the "
        "domain shift under study, not a bug, and is not silently resized away.\n"
    )

    lines.append("## 6. Figures\n")
    lines.append("- `experiments/results/figures/class_counts_per_country.png`")
    lines.append("- `experiments/results/figures/dropped_classes.png`")
    lines.append("- `experiments/results/figures/image_size_distribution.png`\n")

    with open(out_path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))


def main():
    verify_report_path = DATA_DIR / "verification_report.json"
    if not verify_report_path.exists():
        raise SystemExit("Run src/data/verify_dataset.py first (verification_report.json missing).")
    with open(verify_report_path, encoding="utf-8") as f:
        verify_report = json.load(f)

    FIGURES_DIR.mkdir(parents=True, exist_ok=True)

    stats = {}
    for country_entry in verify_report["countries"]:
        country = country_entry["country"]
        country_dir = DATA_DIR / country
        print(f"Parsing annotations for {country}...")
        stats[country] = parse_country_annotations(country_dir)

    with open(DATA_DIR / "class_distribution.json", "w", encoding="utf-8") as f:
        json.dump(stats, f, indent=2)

    print("Generating plots...")
    plot_class_counts_per_country(stats)
    plot_dropped_classes(stats)
    plot_image_size_distribution(stats)

    print("Writing data/DATA_REPORT.md...")
    build_data_report(verify_report, stats, DATA_DIR / "DATA_REPORT.md")
    print("Done.")


if __name__ == "__main__":
    main()
